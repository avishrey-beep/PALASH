import React, { useCallback, useState } from 'react';
import { useRouter, useFocusEffect } from 'expo-router';
import { Screen, Button, WorksheetCard, EmptyState, LoadingState } from '@/components';
import { worksheetService } from '@/services';
import type { Worksheet } from '@/types';

export default function SheetsScreen() {
  const router = useRouter();
  const [worksheets, setWorksheets] = useState<Worksheet[] | null>(null);

  useFocusEffect(
    useCallback(() => {
      let active = true;
      worksheetService.list().then((items) => {
        if (active) setWorksheets(items);
      });
      return () => {
        active = false;
      };
    }, []),
  );

  return (
    <Screen
      title="Worksheets"
      subtitle="Template scaffolds — you complete the content"
      headerRight={<Button title="New" icon="add" size="sm" onPress={() => router.push('/worksheet/create')} />}
    >
      {worksheets === null ? (
        <LoadingState label="Loading worksheets…" />
      ) : worksheets.length === 0 ? (
        <EmptyState
          icon="document-text-outline"
          title="No worksheets yet"
          message="Create a template worksheet to hand out in class. You fill in the questions — nothing is auto-generated by AI."
          actionLabel="New worksheet"
          onAction={() => router.push('/worksheet/create')}
        />
      ) : (
        worksheets.map((w) => (
          <WorksheetCard key={w.id} worksheet={w} onPress={() => router.push(`/worksheet/${w.id}`)} />
        ))
      )}
    </Screen>
  );
}
